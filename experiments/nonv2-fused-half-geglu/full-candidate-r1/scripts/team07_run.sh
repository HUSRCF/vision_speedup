    smoke|full|case-v2|case-stackbox|case-dual|case-pencils|case-g1) ;;
    *) echo 'Usage: team07_run.sh [baseline-smoke|smoke|full|case-v2|case-stackbox|case-dual|case-pencils|case-g1] [GPU index]' >&2; exit 2 ;;
