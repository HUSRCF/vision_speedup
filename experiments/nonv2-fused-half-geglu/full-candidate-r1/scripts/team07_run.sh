    echo "Unable to parse GPU ${gpu} memory usage: ${memory_used}" >&2
    exit 1
fi
memory_used="${memory_used//[[:space:]]/}"
if (( memory_used > 16 )) && [[ "${UNIFOLM_ALLOW_GPU_RESERVATION:-0}" != 1 && "${quality_only}" != 1 ]]; then
    echo "GPU ${gpu} already has allocated memory (${memory_used} MiB). Choose an idle GPU." >&2
    exit 75
